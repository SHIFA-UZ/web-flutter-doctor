package shifa.doctor.data.consultation

import com.google.common.truth.Truth.assertThat
import org.junit.Test
import shifa.doctor.utils.PdfOp
import shifa.doctor.utils.PdfPage
import kotlin.math.ceil

class VisitSummaryPdfTest {
    // A text's height as lines of half-size-wide characters (the 025-2 test's fake).
    private fun fakeMeasure(
        text: String,
        size: Float,
        bold: Boolean,
        width: Float,
    ): Float {
        if (text.isEmpty()) return 0f
        val perLine = (width / (size * 0.5f)).toInt().coerceAtLeast(1)
        val lines = text.split('\n').sumOf { ceil(it.length.coerceAtLeast(1) / perLine.toFloat()).toInt() }
        return lines * size * 1.2f
    }

    private val classToTest = VisitSummaryPdf(::fakeMeasure) { null }

    // Every expected text is there (a missing one would read as index -1, "before" all the others), in this order.
    private fun assertInOrder(
        all: List<String>,
        order: List<String>,
    ) {
        val at = order.map { t -> all.indexOfFirst { it == t } }
        assertThat(order.filterIndexed { i, _ -> at[i] < 0 }).isEmpty()
        assertThat(at).isInStrictOrder()
    }

    private fun texts(pages: List<PdfPage>) =
        pages.flatMap { p -> p.ops.filterIsInstance<PdfOp.Text>().map { it.text } }

    private val summary =
        VisitSummary(
            appointmentId = 102,
            clinic = "Shifa Demo Clinic",
            endedAt = "Wednesday, 4 November 2026 · 10:05",
            patientName = "Jasur Karimov",
            patientId = 12,
            birthDate = "15.04.1990",
            gender = "Male",
            doctorName = "Ulugbek Karimov",
            profession = "Dentist",
            visitType = "In-person",
            minutes = 25,
            notes = "From Shifa AI\n\nSUBJECTIVE:\nNight pain in 36.\n\nDoctor notes\n\nPulp removal.",
        )

    @Test
    fun `the summary reads header, title, the visit, the notes, then the signatures and a footer`() {
        val pages = classToTest.pages(summary, VisitSummaryLabels())
        val all = texts(pages)
        val order =
            listOf("SHIFA", "Appointment ID 102", "Appointment Summary", "Jasur Karimov", "#12", "Ulugbek Karimov · Dentist", "25 min", "Clinical notes", "Night pain in 36.", "Pulp removal.", "Signatures", "Patient's signature")
        assertInOrder(all, order)
        assertThat(all).contains("Page 1 / 1")
        assertThat(all).contains("Generated by Shifa · Confidential")
        // Not signed: no image and no "signed electronically".
        assertThat(pages.single().ops.none { it is PdfOp.Image }).isTrue()
        assertThat(all.none { it.startsWith("Signed electronically") }).isTrue()
    }

    @Test
    fun `a dental visit lists its services by tooth, general last, with totals per currency and its notes`() {
        val dental =
            shifa.doctor.data.model.DentalRecord(
                teeth =
                    mapOf(
                        "__general__" to
                            listOf(
                                shifa.doctor.data.model.ToothServiceLine(
                                    title = "X-ray",
                                    amountMinor = 2_500,
                                    currency = "USD",
                                ),
                            ),
                        "36" to
                            listOf(
                                shifa.doctor.data.model.ToothServiceLine(title = "Filling", amountMinor = 60_000_000),
                            ),
                        "16" to
                            listOf(
                                shifa.doctor.data.model.ToothServiceLine(title = "Cleaning", amountMinor = 10_000_000),
                            ),
                    ),
                discountPercent = 10.0,
                notes = "Lidocaine 2%.",
            )
        val all = texts(classToTest.pages(summary.copy(notes = "", dental = dental), VisitSummaryLabels()))
        val order =
            listOf("DENTAL VISIT — Procedures by tooth", "Tooth", "16", "Cleaning", "36", "Filling", "General", "X-ray", "Discount: 10%", "Lidocaine 2%.", "Signatures")
        assertInOrder(all, order)
        val money = shifa.doctor.utils.Money::format
        assertThat(all).contains("Subtotal: ${money(70_000_000, "UZS")} + ${money(2_500, "USD")}")
        assertThat(all).contains("Total due: ${money(63_000_000, "UZS")} + ${money(2_250, "USD")}")
        // A discount over 100 prints as the 100 % it is saved as.
        val over =
            texts(classToTest.pages(summary.copy(dental = dental.copy(discountPercent = 150.0)), VisitSummaryLabels()))
        assertThat(over).contains("Discount: 100%")
        // No notes written: no empty notes section.
        assertThat(all).doesNotContain("Clinical notes")
    }

    @Test
    fun `the plan section shows the totals, the lines completed this visit and its payment`() {
        val plan =
            VisitSummaryPlan(
                title = "Upper jaw",
                totalMinor = 30_000_000,
                paidMinor = 10_000_000,
                owedMinor = 20_000_000,
                currency = "UZS",
                lines =
                    listOf(
                        PlanSummaryLine("16", "Filling", 6_000_000, "UZS"),
                        PlanSummaryLine(null, "Cleaning", 1_000_000, "UZS"),
                    ),
                payment = 5_000_000L to "Cash",
            )
        val all = texts(classToTest.pages(summary.copy(plan = plan), VisitSummaryLabels()))
        val money = shifa.doctor.utils.Money::format
        val order =
            listOf(
                "Treatment plan", "Upper jaw",
                "Plan total: ${money(
                    30_000_000,
                    "UZS",
                )}",
                "Outstanding: ${money(
                    20_000_000,
                    "UZS",
                )}",
                "Completed this visit", "16", "Filling", "General", "Cleaning",
                "Payment this visit (Cash): ${money(
                    5_000_000,
                    "UZS",
                )}",
                "Signatures",
            )
        assertInOrder(all, order)
    }

    @Test
    fun `before and after photos follow the summary, one page each with its label`() {
        val pages =
            classToTest.pages(
                summary.copy(
                    photos = listOf("Before Treatment" to byteArrayOf(1), "After Treatment" to byteArrayOf(2)),
                ),
                VisitSummaryLabels(),
            )
        assertThat(pages).hasSize(3)
        assertThat(texts(listOf(pages[1]))).contains("Before Treatment")
        assertThat(pages[1].ops.filterIsInstance<PdfOp.Image>().single().bytes.single()).isEqualTo(1.toByte())
        assertThat(texts(listOf(pages[2]))).contains("After Treatment")
        assertThat(texts(listOf(pages[2]))).contains("Page 3 / 3")
        assertThat(pages[2].ops.filterIsInstance<PdfOp.Image>().single().bytes.single()).isEqualTo(2.toByte())
    }

    @Test
    fun `long notes flow onto more pages, each with its page number, and a signature is drawn with its date`() {
        val long = (1..120).joinToString("\n") { "Line $it of the doctor's notes about the visit." }
        val png = byteArrayOf(-119, 80, 78, 71)
        val signed =
            summary.copy(
                notes = long,
                signatureBase64 = "data:image/png;base64," + kotlin.io.encoding.Base64.encode(png),
                signedOn = "04.11.2026 10:01",
            )
        val pages = classToTest.pages(signed, VisitSummaryLabels())
        assertThat(pages.size).isAtLeast(2)
        val all = texts(pages)
        assertThat(all).contains("Page 1 / ${pages.size}")
        assertThat(all).contains("Page ${pages.size} / ${pages.size}")
        assertThat(all).contains("Line 120 of the doctor's notes about the visit.")
        assertThat(pages.last().ops.filterIsInstance<PdfOp.Image>().single().bytes.toList()).isEqualTo(png.toList())
        assertThat(all).contains("Signed electronically on 04.11.2026 10:01 via the SHIFA Patient App")
        // Nothing drawn under the bottom margin except the footer.
        pages.forEach { p ->
            p.ops.filterIsInstance<PdfOp.Text>().filter {
                !it.text.startsWith("Page") && !it.text.startsWith("Generated")
            }.forEach {
                assertThat(it.y).isLessThan(VisitSummaryPdf.PAGE_H - VisitSummaryPdf.MARGIN)
            }
        }
    }

    @Test
    fun `the signatures band never stays alone at a page's foot`() {
        // Notes that end just above the bottom: the band and its lines move to the next page together.
        for (lines in 20..60) {
            val notes = (1..lines).joinToString("\n") { "Line $it" }
            val pages = classToTest.pages(summary.copy(notes = notes), VisitSummaryLabels())
            val page = pages.indexOfFirst { p -> p.ops.any { it is PdfOp.Text && it.text == "Signatures" } }
            assertThat(pages[page].ops.any { it is PdfOp.Text && it.text == "Patient's signature" }).isTrue()
        }
    }

    /**
     * PDF-02's golden: every drawn piece of the full summary (header, the visit, notes, dental, plan, signatures, photo
     * pages, footers) with its page, position, size and weight, against `golden/visit_summary.txt`. A change to the
     * layout shows here as a diff; when it is meant, record again with `RECORD_GOLDEN=1`.
     */
    @Test
    fun `the full summary matches its golden layout`() {
        val dental =
            shifa.doctor.data.model.DentalRecord(
                teeth =
                    mapOf(
                        "36" to
                            listOf(
                                shifa.doctor.data.model.ToothServiceLine(
                                    title = "Pulp removal",
                                    amountMinor = 45_000_000,
                                ),
                            ),
                        "__general__" to
                            listOf(
                                shifa.doctor.data.model.ToothServiceLine(
                                    title = "X-ray",
                                    amountMinor = 2_500,
                                    currency = "USD",
                                ),
                            ),
                    ),
                discountPercent = 10.0,
                notes = "Lidocaine 2%.",
            )
        val plan =
            VisitSummaryPlan(
                "Treatment of 36",
                totalMinor = 230_000_000,
                paidMinor = 100_000_000,
                owedMinor = 130_000_000,
                currency = "UZS",
                lines = listOf(PlanSummaryLine("36", "Root canal treatment", 80_000_000, "UZS")),
                payment = 50_000_000L to "Cash",
            )
        val full =
            summary.copy(
                dental = dental,
                plan = plan,
                photos = listOf("Before Treatment" to byteArrayOf(1)),
                signatureBase64 = kotlin.io.encoding.Base64.encode(byteArrayOf(-119, 80, 78, 71)),
                signedOn = "04.11.2026 10:01",
            )
        val drawn =
            classToTest.pages(full, VisitSummaryLabels()).flatMapIndexed { i, page ->
                page.ops.map { op ->
                    when (op) {
                        is PdfOp.Text -> "p${i + 1} text ${op.x.toInt()},${op.y.toInt()} ${op.size}${if (op.bold) " bold" else ""} ${op.text}"
                        is PdfOp.Image -> "p${i + 1} image ${op.x.toInt()},${op.y.toInt()} ${op.width.toInt()}x${op.height.toInt()}"
                        is PdfOp.Line -> "p${i + 1} line ${op.x1.toInt()},${op.y1.toInt()}-${op.x2.toInt()},${op.y2.toInt()}"
                        is PdfOp.Rect -> "p${i + 1} rect ${op.x.toInt()},${op.y.toInt()} ${op.width.toInt()}x${op.height.toInt()}"
                        else -> "p${i + 1} ${op::class.simpleName}"
                    }
                }
            }.joinToString("\n")
        val golden = java.io.File("src/androidUnitTest/resources/golden/visit_summary.txt")
        if (System.getenv("RECORD_GOLDEN") == "1") {
            golden.parentFile.mkdirs()
            golden.writeText(drawn + "\n")
            // Recording never passes: a flag left on can't accept a regression. Run again without it to verify.
            org.junit.Assert.fail("Golden recorded to ${golden.path}; run again without RECORD_GOLDEN to verify.")
        }
        assertThat(drawn + "\n").isEqualTo(golden.readText())
    }

    @Test
    fun `a Russian summary carries its labels and Cyrillic text through`() {
        val labels =
            VisitSummaryLabels(
                title = "Итоги приёма",
                patient = "Пациент",
                notes = "Клинические заметки",
                signatures = "Подписи",
                dental = "СТОМАТОЛОГИЧЕСКИЙ ВИЗИТ — процедуры по зубам",
                tooth = "Зуб",
                total = "Итого к оплате",
            )
        val ru =
            summary.copy(
                patientName = "Жасур Каримов",
                notes = "Боль в 36 ночью.",
                dental =
                    shifa.doctor.data.model.DentalRecord(
                        teeth =
                            mapOf(
                                "36" to
                                    listOf(
                                        shifa.doctor.data.model.ToothServiceLine(
                                            title = "Удаление пульпы",
                                            amountMinor = 45_000_000,
                                        ),
                                    ),
                            ),
                    ),
            )
        val all = texts(classToTest.pages(ru, labels))
        val order =
            listOf(
                "Итоги приёма",
                "Жасур Каримов",
                "Клинические заметки",
                "Боль в 36 ночью.",
                "СТОМАТОЛОГИЧЕСКИЙ ВИЗИТ — процедуры по зубам",
                "Зуб",
                "Удаление пульпы",
                "Подписи",
            )
        assertInOrder(all, order)
        assertThat(all.any { it.startsWith("Итого к оплате: ") }).isTrue()
    }
}
