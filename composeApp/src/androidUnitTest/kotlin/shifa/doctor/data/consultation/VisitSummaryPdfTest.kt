package shifa.doctor.data.consultation

import com.google.common.truth.Truth.assertThat
import org.junit.Test
import shifa.doctor.utils.PdfOp
import shifa.doctor.utils.PdfPage
import kotlin.math.ceil

class VisitSummaryPdfTest {
    // A text's height as lines of half-size-wide characters (the 025-2 test's fake).
    private fun fakeMeasure(
        text: String,
        size: Float,
        bold: Boolean,
        width: Float,
    ): Float {
        if (text.isEmpty()) return 0f
        val perLine = (width / (size * 0.5f)).toInt().coerceAtLeast(1)
        val lines = text.split('\n').sumOf { ceil(it.length.coerceAtLeast(1) / perLine.toFloat()).toInt() }
        return lines * size * 1.2f
    }

    private val classToTest = VisitSummaryPdf(::fakeMeasure) { null }

    private fun texts(pages: List<PdfPage>) =
        pages.flatMap { p -> p.ops.filterIsInstance<PdfOp.Text>().map { it.text } }

    private val summary =
        VisitSummary(
            appointmentId = 102,
            clinic = "Shifa Demo Clinic",
            endedAt = "Wednesday, 4 November 2026 · 10:05",
            patientName = "Jasur Karimov",
            patientId = 12,
            birthDate = "15.04.1990",
            gender = "Male",
            doctorName = "Ulugbek Karimov",
            profession = "Dentist",
            visitType = "In-person",
            minutes = 25,
            notes = "From Shifa AI\n\nSUBJECTIVE:\nNight pain in 36.\n\nDoctor notes\n\nPulp removal.",
        )

    @Test
    fun `the summary reads header, title, the visit, the notes, then the signatures and a footer`() {
        val pages = classToTest.pages(summary, VisitSummaryLabels())
        val all = texts(pages)
        val order =
            listOf("SHIFA", "Appointment ID 102", "Appointment Summary", "Jasur Karimov", "#12", "Ulugbek Karimov · Dentist", "25 min", "Clinical notes", "Night pain in 36.", "Pulp removal.", "Signatures", "Patient's signature")
        assertThat(order.map { t -> all.indexOfFirst { it == t } }).isInStrictOrder()
        assertThat(all).contains("Page 1 / 1")
        assertThat(all).contains("Generated by Shifa · Confidential")
        // Not signed: no image and no "signed electronically".
        assertThat(pages.single().ops.none { it is PdfOp.Image }).isTrue()
        assertThat(all.none { it.startsWith("Signed electronically") }).isTrue()
    }

    @Test
    fun `long notes flow onto more pages, each with its page number, and a signature is drawn with its date`() {
        val long = (1..120).joinToString("\n") { "Line $it of the doctor's notes about the visit." }
        val png = byteArrayOf(-119, 80, 78, 71)
        val signed =
            summary.copy(
                notes = long,
                signatureBase64 = "data:image/png;base64," + kotlin.io.encoding.Base64.encode(png),
                signedOn = "04.11.2026 10:01",
            )
        val pages = classToTest.pages(signed, VisitSummaryLabels())
        assertThat(pages.size).isAtLeast(2)
        val all = texts(pages)
        assertThat(all).contains("Page 1 / ${pages.size}")
        assertThat(all).contains("Page ${pages.size} / ${pages.size}")
        assertThat(all).contains("Line 120 of the doctor's notes about the visit.")
        assertThat(pages.last().ops.filterIsInstance<PdfOp.Image>().single().bytes.toList()).isEqualTo(png.toList())
        assertThat(all).contains("Signed electronically on 04.11.2026 10:01 via the SHIFA Patient App")
        // Nothing drawn under the bottom margin except the footer.
        pages.forEach { p ->
            p.ops.filterIsInstance<PdfOp.Text>().filter {
                !it.text.startsWith("Page") && !it.text.startsWith("Generated")
            }.forEach {
                assertThat(it.y).isLessThan(VisitSummaryPdf.PAGE_H - VisitSummaryPdf.MARGIN)
            }
        }
    }

    @Test
    fun `the signatures band never stays alone at a page's foot`() {
        // Notes that end just above the bottom: the band and its lines move to the next page together.
        for (lines in 20..60) {
            val notes = (1..lines).joinToString("\n") { "Line $it" }
            val pages = classToTest.pages(summary.copy(notes = notes), VisitSummaryLabels())
            val page = pages.indexOfFirst { p -> p.ops.any { it is PdfOp.Text && it.text == "Signatures" } }
            assertThat(pages[page].ops.any { it is PdfOp.Text && it.text == "Patient's signature" }).isTrue()
        }
    }
}
