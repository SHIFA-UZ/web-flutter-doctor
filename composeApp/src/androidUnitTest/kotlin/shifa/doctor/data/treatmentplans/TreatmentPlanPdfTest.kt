package shifa.doctor.data.treatmentplans

import com.google.common.truth.Truth.assertThat
import org.junit.Test
import shifa.doctor.data.model.InstallmentItem
import shifa.doctor.data.model.InstallmentPlan
import shifa.doctor.data.model.PlanLine
import shifa.doctor.data.model.TreatmentPlanDetail
import shifa.doctor.data.model.TreatmentPlanSummary
import shifa.doctor.utils.PdfOp
import shifa.doctor.utils.PdfPage
import kotlin.math.ceil

class TreatmentPlanPdfTest {
    // A text's height as lines of half-size-wide characters (the visit summary test's fake).
    private fun fakeMeasure(
        text: String,
        size: Float,
        bold: Boolean,
        width: Float,
    ): Float {
        if (text.isEmpty()) return 0f
        val perLine = (width / (size * 0.5f)).toInt().coerceAtLeast(1)
        val lines = text.split('\n').sumOf { ceil(it.length.coerceAtLeast(1) / perLine.toFloat()).toInt() }
        return lines * size * 1.2f
    }

    private fun m(minor: Long) = shifa.doctor.utils.Money.format(minor, "UZS")

    private val classToTest = TreatmentPlanPdf(::fakeMeasure) { null }

    private fun texts(pages: List<PdfPage>) =
        pages.flatMap { p -> p.ops.filterIsInstance<PdfOp.Text>().map { it.text } }

    private fun assertInOrder(
        all: List<String>,
        order: List<String>,
    ) {
        val at = order.map { t -> all.indexOfFirst { it == t } }
        assertThat(order.filterIndexed { i, _ -> at[i] < 0 }).isEmpty()
        assertThat(at).isInStrictOrder()
    }

    private fun line(
        id: Long,
        title: String,
        tooth: String?,
        order: Int,
        total: Long = 80_000_000,
    ) = PlanLine(
        id,
        title = title,
        unitPriceMinor = total,
        lineTotalMinor = total,
        sortOrder = order,
        statusRaw = "PLANNED",
        specialtyMetadata = tooth?.let { """{"fdi":"$it"}""" },
    )

    private val plan =
        TreatmentPlanDetail(
            TreatmentPlanSummary(
                501, 1, 12, "Jasur Karimov", title = "Molars", diagnosis = "K04.0", statusRaw = "ACTIVE",
                notes = "Night pain.\n\nCheck in 2 weeks.", symptoms = listOf("pain", " "),
                totalMinor = 240_000_000, paidMinor = 100_000_000, owedMinor = 140_000_000,
            ),
            listOf(
                line(3, "Hygiene", null, 2),
                line(2, "Crown", "46", 1),
                line(1, "Root canal", "36", 0),
                line(4, "Filling", "6", 3),
            ),
            installmentPlans =
                listOf(
                    InstallmentPlan(
                        61,
                        "ACTIVE",
                        140_000_000,
                        "UZS",
                        listOf(
                            InstallmentItem(802, 2, 70_000_000, dueDate = "2027-01-01", status = "PENDING"),
                            InstallmentItem(801, 1, 70_000_000, dueDate = "2026-12-01", status = "PAID"),
                        ),
                    ),
                ),
        )

    private val data =
        TreatmentPlanPdfData(plan, "Shifa Demo Clinic", "06.11.2026 14:05", "01.11.2026", null, "Aziza Karimova")

    @Test
    fun `the plan reads header, summary, notes, lines by tooth with others last, schedule, signature, footer`() {
        val pages = classToTest.pages(data, TreatmentPlanPdfLabels())
        val all = texts(pages)
        assertInOrder(
            all,
            listOf(
                "SHIFA", "Shifa Demo Clinic", "Plan ID: #501", "Generated: 06.11.2026 14:05", "Treatment Plan · Molars",
                "Plan summary", "Jasur Karimov", "#12", "K04.0", "Aziza Karimova", "Active", m(240_000_000),
                m(140_000_000), "01.11.2026", "Symptoms / complaints", "• pain", "Plan notes", "Night pain.",
                "Check in 2 weeks.", "Procedures & line items",
                // Teeth by number (6 before 36), then the lines without one.
                "Tooth 6 (FDI)", "Filling", "Tooth 36 (FDI)", "Root canal", "Tooth 46 (FDI)", "Crown", "Other services", "Hygiene",
                "Installment schedules",
                "#61 · ACTIVE · " +
                    m(
                        140_000_000,
                    ),
                "2026-12-01", "PAID", "2027-01-01", "PENDING",
                "Patient acknowledgement & signature", "Patient: Jasur Karimov", "Patient signature", "Date",
            ),
        )
        // No "Updated" row without a date; a blank symptom is left out; the line has no discount.
        assertThat(all).doesNotContain("Updated")
        assertThat(all).doesNotContain("• ")
        assertThat(all).contains("—")
        // Every page has its footer with the page count.
        assertThat(all.count { it.startsWith("Generated by SHIFA") }).isEqualTo(pages.size)
        assertThat(all).contains("Page 1 / ${pages.size}")
    }

    @Test
    fun `many lines flow over pages, every row inside the page, the signature block kept together`() {
        val many =
            plan.copy(
                lines = (1..80L).map { line(it, "Service $it with a longer name to wrap", null, it.toInt()) },
            )
        val pages = classToTest.pages(data.copy(plan = many), TreatmentPlanPdfLabels())
        assertThat(pages.size).isAtLeast(3)
        assertInsideMargins(pages)
        val last = texts(listOf(pages.last()))
        assertThat(last).containsAtLeast("Patient acknowledgement & signature", "Patient signature", "Date")
        // Without teeth: one table, no tooth headings.
        assertThat(texts(pages).none { it.startsWith("Tooth ") }).isTrue()
    }

    // Every text (but the footer) ends above the bottom margin: its origin plus its measured height.
    private fun assertInsideMargins(pages: List<PdfPage>) {
        val bottom = TreatmentPlanPdf.PAGE_H - TreatmentPlanPdf.MARGIN
        pages.forEach { page ->
            page.ops.filterIsInstance<PdfOp.Text>().filter { it.y < bottom }.forEach {
                assertThat(it.y + fakeMeasure(it.text, it.size, it.bold, it.width)).isAtMost(bottom + 0.01f)
            }
        }
    }

    @Test
    fun `a huge diagnosis flows over pages, a tooth heading stays with its first row, a schedule shows its own status`() {
        val long = (1..700).joinToString(" ") { "word$it" }
        val teeth = (11..48).filter { it % 10 in 1..8 }.map { "$it" }
        val big =
            plan.copy(
                summary = plan.summary.copy(diagnosis = long),
                lines =
                    teeth.mapIndexed {
                            i,
                            t,
                        ->
                        line(i.toLong() + 1, "Service on $t with a long name that wraps in the column", t, i)
                    },
            )
        val labels =
            TreatmentPlanPdfLabels(scheduleStatus = {
                if (it == "ACTIVE") "Active" else it
            }, installmentStatus = { it.lowercase() })
        val pages = classToTest.pages(data.copy(plan = big), labels)
        assertInsideMargins(pages)
        assertThat(texts(pages)).contains("#61 · Active · " + m(140_000_000))
        assertThat(texts(pages)).containsAtLeast("paid", "pending")
        // Each "Tooth" heading has its first line on the same page.
        pages.forEach { page ->
            val t = page.ops.filterIsInstance<PdfOp.Text>().map { it.text }
            t.forEachIndexed { i, text ->
                if (text.startsWith("Tooth ")) {
                    val fdi = text.removePrefix("Tooth ").removeSuffix(" (FDI)")
                    assertThat(t.drop(i)).contains("Service on $fdi with a long name that wraps in the column")
                }
            }
        }
    }

    @Test
    fun `the render gets the pages`() {
        var got: List<PdfPage>? = null
        val bytes =
            TreatmentPlanPdf(::fakeMeasure) {
                got = it
                byteArrayOf(1)
            }.pdf(data, TreatmentPlanPdfLabels())
        assertThat(bytes).isEqualTo(byteArrayOf(1))
        assertThat(got).isNotEmpty()
    }
}
