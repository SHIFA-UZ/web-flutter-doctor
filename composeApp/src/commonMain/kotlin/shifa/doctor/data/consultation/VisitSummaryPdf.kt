/** What the visit summary says (PDF-01): names, times and texts already in the app's language and the practice's zone. */
data class VisitSummary(
    val appointmentId: Long,
    val clinic: String?,
    // "Wednesday, 4 November 2026 · 10:05": when the visit ended.
    val endedAt: String,
    val patientName: String,
    val patientId: Long?,
    val birthDate: String?,
    val gender: String?,
    val doctorName: String,
    val profession: String?,
    val visitType: String,
    val minutes: Int?,
    // The documentation text (Shifa AI's block first, then the doctor's: composeVisitDocumentationText).
    val notes: String,
    val signatureBase64: String? = null,
    val signedOn: String? = null,
    // DENTAL-02: the services by tooth and their totals; null or without lines leaves the section out.
    val dental: DentalRecord? = null,
    // APPT-05: before/after photos, each on a page of its own after the summary: its label and JPEG bytes.
    val photos: List<Pair<String, ByteArray>> = emptyList(),
    // DENTAL-03: the treatment plan's lines completed and the payment recorded in this visit.
    val plan: VisitSummaryPlan? = null,
)

/** A plan line completed in the visit; [tooth] null for a general one. */
data class PlanSummaryLine(
    val tooth: String?,
    val title: String,
    val amountMinor: Long,
    val currency: String,
)

/** The plan section (05 §5, Flutter's `buildPlanPdfSection`, kept once): totals, this visit's lines, its payment. */
data class VisitSummaryPlan(
    val title: String,
    val totalMinor: Long,
    val paidMinor: Long,
    val owedMinor: Long,
    val currency: String,
    val lines: List<PlanSummaryLine>,
    // The amount and the method's label.
    val payment: Pair<Long, String>?,
)

/** The summary's fixed words, in the app's language (the screen resolves them). */
data class VisitSummaryLabels(
    val title: String = "Appointment Summary",
    val appointmentId: (Long) -> String = { "Appointment ID $it" },
    val patient: String = "Patient",
    val patientId: String = "Patient ID",
    val birthDate: String = "Date of Birth",
    val gender: String = "Gender",
    val doctor: String = "Doctor",
    val visitType: String = "Visit type",
    val duration: String = "Duration",
    val minutes: (Int) -> String = { "$it min" },
    val notes: String = "Clinical notes",
    val signatures: String = "Signatures",
    val doctorSignature: String = "Doctor's signature",
    val patientSignature: String = "Patient's signature",
    val signedElectronically: (String) -> String = { "Signed electronically on $it via the SHIFA Patient App" },
    val footer: String = "Generated by Shifa · Confidential",
    val page: (Int, Int) -> String = { p, n -> "Page $p / $n" },
    val dental: String = "DENTAL VISIT — Procedures by tooth",
    val tooth: String = "Tooth",
    val service: String = "Service",
    val amount: String = "Amount",
    val general: String = "General",
    val subtotal: String = "Subtotal",
    val discount: String = "Discount",
    val total: String = "Total due",
    val plan: String = "Treatment plan",
    val planTotal: String = "Plan total",
    val planPaid: String = "Paid",
    val planOutstanding: String = "Outstanding",
    val doneThisVisit: String = "Completed this visit",
    val paymentThisVisit: String = "Payment this visit",
)

/**
 * The visit summary document (PDF-01, spec 05 §6; Flutter's `appointment_pdf_service`) made in the app until the
 * backend renders it (BE-01): portrait A4, the header (SHIFA, the clinic, when the visit ended, its id), the title band,
 * the patient and visit block, the clinical notes (flowing across pages), the signatures (the patient's image and when
 * they signed, or an empty line) and a footer with the page on every page. Flutter's never-filled sections (diagnosis,
 * prescriptions, recommendations, follow-up) are left out. A dental visit adds its services by tooth with the totals
 * per currency (DENTAL-02), then the treatment plan's part (DENTAL-03); before/after photos follow, one per page
 * (APPT-05).
 * Labels come in the app's language (Flutter: en and uz only).
 */
class VisitSummaryPdf(
    private val measure: (text: String, size: Float, bold: Boolean, width: Float) -> Float = ::measurePdfText,
    private val render: (List<PdfPage>) -> ByteArray? = ::renderPdf,
) {
    fun pdf(
        summary: VisitSummary,
        labels: VisitSummaryLabels,
    ): ByteArray? = render(pages(summary, labels))

    fun pages(
        summary: VisitSummary,
        labels: VisitSummaryLabels,
    ): List<PdfPage> = Layout(summary, labels).run()

    private inner class Layout(
        private val s: VisitSummary,
        private val l: VisitSummaryLabels,
    ) : PdfFlow(PAGE_W, PAGE_H, MARGIN, measure) {
        fun run(): List<PdfPage> {
            header()
            sectionHeader(l.title, 15f)
            block()
            if (s.notes.isNotBlank()) {
                sectionHeader(l.notes)
                s.notes.trim().split('\n').forEach { line -> if (line.isBlank()) y += 6 else paragraph(line) }
            }
            s.dental?.takeIf { it.lineCount > 0 || it.notes.isNotBlank() }?.let(::dental)
            s.plan?.let(::plan)
            signatures()
            s.photos.forEach { (label, bytes) ->
                newPage()
                sectionHeader(label)
                ops += PdfOp.Image(margin, y, contentW, bottom - y, bytes)
                y = bottom
            }
            val all = finish()
            return all.mapIndexed { i, page -> PdfPage(page.width, page.height, page.ops + footer(i + 1, all.size)) }
        }

        private fun header() {
            val half = contentW / 2
            ops += PdfOp.Text(margin, y, half, "SHIFA", 20f, bold = true)
            var left = y + measure("SHIFA", 20f, true, half) + 2
            s.clinic?.takeIf { it.isNotBlank() }?.let {
                ops += PdfOp.Text(margin, left, half, it, 10f, gray = 0.35f)
                left += measure(it, 10f, false, half)
            }
            ops += PdfOp.Text(margin + half, y, half, s.endedAt, 10f, align = PdfAlign.End)
            val idLine = l.appointmentId(s.appointmentId)
            val right = y + measure(s.endedAt, 10f, false, half) + 2
            ops += PdfOp.Text(margin + half, right, half, idLine, 10f, gray = 0.35f, align = PdfAlign.End)
            y = maxOf(left, right + measure(idLine, 10f, false, half)) + 8
            ops += PdfOp.Line(margin, y, pageW - margin, y, gray = 0.5f, width = 1.5f)
            y += 4
        }

        /** The patient and the visit, label and value per row. */
        private fun block() {
            val rows =
                listOfNotNull(
                    l.patient to s.patientName,
                    s.patientId?.let { l.patientId to "#$it" },
                    s.birthDate?.let { l.birthDate to it },
                    s.gender?.let { l.gender to it },
                    l.doctor to
                        listOfNotNull(
                            s.doctorName,
                            s.profession?.takeIf { it.isNotBlank() },
                        ).joinToString(" · "),
                    l.visitType to s.visitType,
                    s.minutes?.let { l.duration to l.minutes(it) },
                )
            val valueW = contentW - LABEL_W
            rows.forEach { (label, value) ->
                val h = maxOf(measure(value, 11f, false, valueW), measure(label, 11f, true, LABEL_W)) + 4
                need(h)
                ops += PdfOp.Text(margin, y, LABEL_W, label, 11f, bold = true, gray = 0.3f)
                ops += PdfOp.Text(margin + LABEL_W, y, valueW, value, 11f)
                y += h
            }
        }

        /** A table row: tooth, service (wraps), amount (right-aligned). */
        private fun row(
            tooth: String,
            service: String,
            amount: String,
            bold: Boolean = false,
        ) {
            val amountW = 110f
            val serviceW = contentW - TOOTH_W - amountW
            val h = maxOf(measure(service, 10f, bold, serviceW), measure(amount, 10f, bold, amountW)) + 4
            need(h)
            ops += PdfOp.Text(margin, y, TOOTH_W, tooth, 10f, bold = bold)
            ops += PdfOp.Text(margin + TOOTH_W, y, serviceW, service, 10f, bold = bold)
            ops += PdfOp.Text(margin + TOOTH_W + serviceW, y, amountW, amount, 10f, bold = bold, align = PdfAlign.End)
            y += h
        }

        /** The plan, its totals, the lines this visit completed and the payment it recorded. */
        private fun plan(p: VisitSummaryPlan) {
            sectionHeader(l.plan)
            paragraph(p.title, bold = true)
            paragraph("${l.planTotal}: ${Money.format(p.totalMinor, p.currency)}")
            paragraph("${l.planPaid}: ${Money.format(p.paidMinor, p.currency)}")
            paragraph("${l.planOutstanding}: ${Money.format(p.owedMinor, p.currency)}")
            if (p.lines.isNotEmpty()) {
                y += 4
                paragraph(l.doneThisVisit, bold = true)
                row(l.tooth, l.service, l.amount, bold = true)
                p.lines.forEach { row(it.tooth ?: l.general, it.title, Money.format(it.amountMinor, it.currency)) }
            }
            p.payment?.let { (minor, method) ->
                y += 4
                paragraph("${l.paymentThisVisit} ($method): ${Money.format(minor, p.currency)}")
            }
        }

        /**
         * Tooth, service and amount per line (teeth in chart order, general last), the totals per currency, then the
         * dental clinical notes.
         */
        private fun dental(record: DentalRecord) {
            sectionHeader(l.dental)
            if (record.lineCount > 0) row(l.tooth, l.service, l.amount, bold = true)
            val order = DentalChartCodec.teeth(record.dentitionKind) + DentalChartCodec.GENERAL_KEY
            val keys = order.filter { it in record.teeth } + record.teeth.keys.filter { it !in order }
            keys.forEach { key ->
                val tooth = if (key == DentalChartCodec.GENERAL_KEY) l.general else key
                record.teeth[key].orEmpty().forEach { row(tooth, it.title, Money.format(it.amountMinor, it.currency)) }
            }
            y += 4
            val sums = { m: Map<String, Long> -> m.entries.joinToString(" + ") { (c, v) -> Money.format(v, c) } }
            if (record.subtotals.isNotEmpty()) {
                paragraph("${l.subtotal}: ${sums(record.subtotals)}")
                val discount = record.discountPercent.coerceIn(0.0, 100.0)
                if (discount > 0) paragraph("${l.discount}: ${percentText(discount)}%")
                paragraph("${l.total}: ${sums(record.totals)}", bold = true)
            }
            record.notes.trim().takeIf(String::isNotEmpty)?.let {
                y += 6
                it.split('\n').forEach { line -> if (line.isBlank()) y += 6 else paragraph(line) }
            }
        }

        @OptIn(ExperimentalEncodingApi::class)
        private fun signatures() {
            val half = contentW / 2 - 8
            val image =
                s.signatureBase64?.trim()?.takeIf(String::isNotEmpty)?.let { raw ->
                    runCatching {
                        Base64.decode(
                            raw.substringAfter(",", raw).trim(),
                        )
                    }.getOrNull()?.takeIf { it.isNotEmpty() }
                }
            val doctorLabel = "${l.doctorSignature}: ${s.doctorName}"
            val caption = s.signedOn?.takeIf { image != null }?.let(l.signedElectronically)
            val labelsH = maxOf(measure(doctorLabel, 10f, false, half), measure(l.patientSignature, 10f, false, half))
            val captionH = caption?.let { measure(it, 9f, false, half) + 2 } ?: 0f
            // The whole block on one page, its heading included (no band left alone at a page's foot).
            val bandH = 14 + measure(l.signatures, 14f, true, contentW - 16) + 12 + 4
            need(bandH + 8 + SIGNATURE_H + 4 + labelsH + 2 + captionH)
            sectionHeader(l.signatures)
            y += 8
            // The doctor signs on paper (a line); the patient's signature from the app, or a line to sign on.
            ops += PdfOp.Line(margin, y + SIGNATURE_H, margin + half, y + SIGNATURE_H, gray = 0.3f)
            val right = margin + contentW - half
            if (image != null) {
                ops += PdfOp.Image(right, y, half, SIGNATURE_H - 4, image)
            }
            ops += PdfOp.Line(right, y + SIGNATURE_H, right + half, y + SIGNATURE_H, gray = 0.3f)
            y += SIGNATURE_H + 4
            ops += PdfOp.Text(margin, y, half, doctorLabel, 10f, gray = 0.35f)
            ops += PdfOp.Text(right, y, half, l.patientSignature, 10f, gray = 0.35f)
            y += labelsH + 2
            caption?.let {
                ops += PdfOp.Text(right, y, half, it, 9f, gray = 0.35f)
                y += captionH
            }
        }

        private fun footer(
            page: Int,
            pages: Int,
        ): List<PdfOp> {
            val fy = pageH - margin + 12
            return listOf(
                PdfOp.Line(margin, fy - 4, pageW - margin, fy - 4, gray = 0.8f),
                PdfOp.Text(margin, fy, contentW / 2, l.footer, 8f, gray = 0.45f),
                PdfOp.Text(
                    margin + contentW / 2,
                    fy,
                    contentW / 2,
                    l.page(page, pages),
                    8f,
                    gray = 0.45f,
                    align = PdfAlign.End,
                ),
            )
        }
    }

    companion object {
        // Portrait A4 in points, 40 pt margins (Flutter's page).
        const val PAGE_W = 595f
        const val PAGE_H = 842f
        const val MARGIN = 40f
        private const val LABEL_W = 140f
        private const val SIGNATURE_H = 60f
        private const val TOOTH_W = 60f
    }
}
