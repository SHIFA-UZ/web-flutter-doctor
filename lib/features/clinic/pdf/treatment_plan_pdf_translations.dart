  String labelPlanStatus(String raw) {
    switch (raw.toUpperCase()) {
      case 'DRAFT':
        return _lbl('Draft', 'Loyiha');
      case 'ACTIVE':
        return _lbl('Active', 'Faol');
      case 'ON_HOLD':
        return _lbl('On hold', 'To\'xtatilgan');
      case 'IN_PROGRESS':
        return _lbl('In progress', 'Jarayonda');
      case 'COMPLETED':
        return _lbl('Completed', 'Yakunlangan');
      case 'CANCELLED':
        return _lbl('Cancelled', 'Bekor qilingan');
      default:
        return raw;
    }
  }

  String labelPaymentStatus(String raw) {
    switch (raw.toUpperCase()) {
      case 'PAID':
        return _lbl('Paid', 'To\'langan');
      case 'PARTIAL':
        return _lbl('Partial', 'Qisman');
      case 'UNPAID':
        return _lbl('Unpaid', 'To\'lanmagan');
      case 'NONE':
      default:
        return raw.isEmpty ? '—' : raw;
    }
  }

  String labelLineStatus(String raw) {
