        return _lbl('Paid', 'To\'langan');
      case 'OVERDUE':
        return _lbl('Overdue', 'Muddati o\'tgan');
      case 'WAIVED':
        return _lbl('Waived', 'Yechildi');
      case 'CANCELLED':
        return _lbl('Cancelled', 'Bekor qilingan');
      default:
        return raw.isEmpty ? '—' : raw;
    }
  }

  String _lbl(String en, String uz) => _lang == 'uz' ? uz : en;
