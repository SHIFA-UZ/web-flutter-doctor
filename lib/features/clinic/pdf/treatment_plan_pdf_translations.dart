  /// Title above the per-duedate installment table for one schedule.
  String installmentScheduleSectionTitle(int installmentPlanId) {
    return _lang == 'uz'
        ? 'Jadval №$installmentPlanId — toʻlov qislari grafigi'
        : 'Schedule #$installmentPlanId — installments by due date';
  }

