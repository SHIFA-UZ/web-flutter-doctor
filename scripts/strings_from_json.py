#!/usr/bin/env python3
"""Generates the Compose string resources from docs/kmp-spec/strings/ (CORE-04).

    python3 scripts/strings_from_json.py

Reads {en,uz,ru}.json (flat key -> text) and plurals.json, writes
composeApp/src/commonMain/composeResources/values{,-uz,-ru}/strings.xml and plurals.xml.
Placeholders {x}, {{x}}, %s and %d become positional %1$s / %1$d, numbered in the order the ENGLISH text
uses them, so a translation that reorders them keeps the same argument numbers.
Keys listed under a plural's "replaces" are left out of strings.xml. Re-run after editing the JSON;
never edit the generated XML by hand.
"""
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "docs/kmp-spec/strings"
OUT = ROOT / "composeApp/src/commonMain/composeResources"
LOCALES = {"en": "values", "uz": "values-uz", "ru": "values-ru"}
PLACEHOLDER = re.compile(r"\{\{(\w+)\}\}|\{(\w+)\}|%[sd]")
HEADER = "<?xml version=\"1.0\" encoding=\"utf-8\"?>\n<!-- Generated by scripts/strings_from_json.py from docs/kmp-spec/strings/. Do not edit. -->\n<resources>\n"


def names(value: str) -> list:
    out = []
    for m in PLACEHOLDER.finditer(value):
        name = m.group(1) or m.group(2) or m.group(0)
        if name not in out:
            out.append(name)
    return out


def convert(value: str, order: list, where: str) -> str:
    def positional(m):
        token = m.group(0)
        name = m.group(1) or m.group(2) or token
        assert name in order, f"{where}: placeholder {token} is not in the English text"
        return f"%{order.index(name) + 1}${'d' if token == '%d' else 's'}"

    v = PLACEHOLDER.sub(positional, value)  # a literal % stays as is: CMP does not unescape %%
    # CMP's plugin unescapes only \n, \t, \uXXXX and \\ (not \' or \"), so quotes stay raw.
    v = v.replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;")
    return v.replace("\\", "\\\\").replace("\n", "\\n").replace("\t", "\\t")


def main():
    plurals = json.loads((SRC / "plurals.json").read_text())
    replaced = {k for p in plurals.values() for k in p.get("replaces", [])}
    en = json.loads((SRC / "en.json").read_text())
    en_keys = set(en)
    for locale, folder in LOCALES.items():
        strings = json.loads((SRC / f"{locale}.json").read_text())
        missing = en_keys - set(strings)
        assert not missing, f"{locale} lacks {sorted(missing)[:10]}"
        extra = set(strings) - en_keys
        assert not extra, f"{locale} has keys en lacks: {sorted(extra)[:10]}"
        d = OUT / folder
        d.mkdir(parents=True, exist_ok=True)
        lines = [
            f'    <string name="{k}">{convert(v, names(en[k]), f"{locale}/{k}")}</string>\n'
            for k, v in sorted(strings.items())
            if k not in replaced
        ]
        (d / "strings.xml").write_text(HEADER + "".join(lines) + "</resources>\n")
        plines = []
        for name, p in sorted(plurals.items()):
            forms = p[locale]
            plines.append(f'    <plurals name="{name}">\n')
            order = names(p["en"]["other"])
            plines += [f'        <item quantity="{q}">{convert(t, order, f"{locale}/{name}")}</item>\n' for q, t in forms.items()]
            plines.append("    </plurals>\n")
        (d / "plurals.xml").write_text(HEADER + "".join(plines) + "</resources>\n")
        print(f"{folder}: {len(lines)} strings, {len(plurals)} plurals")


if __name__ == "__main__":
    main()
